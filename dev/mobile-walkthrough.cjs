// Portrait/mobile UI walkthrough through real clicks + touch swipes.
const { chromium } = require('playwright');
(async () => {
  const [, , out, w = '390', h = '844'] = process.argv;
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: +w, height: +h }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', (e) => errors.push('pageerror: ' + String(e)));
  await page.goto('http://localhost:5173/');
  await page.waitForFunction(() => !!window.__UPRUN__, null, { timeout: 30000 });
  const shot = (name) => page.screenshot({ path: `${out}/${name}.png` });
  const step = (s) => page.evaluate((s) => window.__UPRUN__.engine.stepManual(s), s);
  const info = () => page.evaluate(() => window.__UPRUN__.info());
  await step(1.5); await shot('p01_intro_aerial');
  await step(4); await shot('p02_intro_char');
  await step(1.6); await shot('p03_intro_cap');
  await page.click('text=Skip intro');
  await page.evaluate(() => (window.__UPRUN__.engine.manual = false));
  await page.waitForTimeout(800);
  await shot('p04_title');
  await page.click('text=Main menu');
  await page.waitForTimeout(600);
  await shot('p05_menu');
  await page.click('text=Select Character');
  await page.waitForTimeout(600);
  await page.click('[aria-label="Next character"]');
  await page.waitForTimeout(800);
  await shot('p06_char_yogi');
  await page.click('[aria-label="Next character"]');
  await page.waitForTimeout(800);
  await shot('p07_char_ummeedwar');
  await page.click('[aria-label="Back"]');
  await page.click('text=Missions');
  await page.waitForTimeout(400);
  await shot('p08_missions');
  await page.click('[aria-label="Back"]');
  await page.click('text=Unlocks');
  await page.waitForTimeout(400);
  await shot('p09_shop');
  await page.click('[aria-label="Back"]');
  await page.click('text=Settings');
  await page.waitForTimeout(400);
  await shot('p10_settings');
  await page.click('[aria-label="Back"]');
  await page.click('text=START GAME');
  await page.waitForTimeout(400);
  await shot('p11_modes');
  await page.click('text=Run ▸');
  await page.waitForTimeout(1500);
  // Real touch swipe: left.
  const swipe = async (dx, dy) => {
    const cdp = await ctx.newCDPSession(page);
    const x = +w / 2, y = +h * 0.6;
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
    for (let i = 1; i <= 5; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + (dx * i) / 5, y: y + (dy * i) / 5 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  };
  const lane = () => page.evaluate(() => window.__UPRUN__.engine.sim.player.lane);
  const l0 = await lane();
  await swipe(-120, 0);
  await page.waitForTimeout(300);
  const l1 = await lane();
  await swipe(120, 0);
  await page.waitForTimeout(300);
  const l2 = await lane();
  await swipe(0, -120);
  await page.waitForTimeout(80);
  const air = await page.evaluate(() => !window.__UPRUN__.engine.sim.player.grounded);
  await page.waitForTimeout(800);
  await swipe(0, 120);
  await page.waitForTimeout(60);
  const sliding = await page.evaluate(() => window.__UPRUN__.engine.sim.player.sliding);
  const scrollY = await page.evaluate(() => window.scrollY + document.scrollingElement.scrollTop);
  console.log('SWIPES lane', l0, '->', l1, '->', l2, 'jumped', air, 'slid', sliding, 'scroll', scrollY);
  await page.evaluate(() => { window.__UPRUN__.engine.setAutopilot(true); });
  await page.waitForTimeout(1500);
  await shot('p12_run');
  await page.evaluate(() => window.__UPRUN__.stumble());
  await step(0.3); await shot('p13_stumble');
  await step(0.8); await shot('p14_cine1');
  await step(1.6); await shot('p15_cine2');
  await step(2.0); await shot('p16_chase');
  await page.evaluate(() => (window.__UPRUN__.engine.manual = false));
  await page.click('[aria-label="Pause"]');
  await page.waitForTimeout(400);
  await shot('p17_pause');
  await page.click('text=Resume');
  await page.evaluate(() => { window.__UPRUN__.engine.setAutopilot(false); });
  await page.waitForFunction(() => window.__UPRUN__.info().state === 'GAME_OVER', null, { timeout: 60000 });
  await page.waitForTimeout(1200);
  await shot('p18_over');
  console.log('over', JSON.stringify(await info()));
  console.log('ERRORS\n' + errors.slice(0, 30).join('\n'));
  await browser.close();
})();
